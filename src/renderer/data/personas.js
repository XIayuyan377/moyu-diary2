// 根据今日工作数据智能推荐人设
export function getTodayPersona(stats, gender = 'female') {
  const { workHours, completedTasks, coffeeCount, standCount } = stats
  
  let personaId = 'academic_buddhist' // 默认
  
  if (workHours >= 10) personaId = 'lab_ghost'
  else if (workHours >= 8) personaId = 'ddl_wargod'
  else if (completedTasks === 0) personaId = 'full_slack'
  else if (coffeeCount >= 4) personaId = 'caffeine_overdose'
  else if (standCount === 0) personaId = 'sleep_deprived'
  else {
    // 随机从剩余人设中选
    const idx = new Date().getDate() % PERSONAS.length
    personaId = PERSONAS[idx].id
  }
  
  const persona = PERSONAS.find(p => p.id === personaId) || PERSONAS[0]
  return {
    ...persona,
    image: `avatars/${gender}/${persona.name}.png`
  }
}